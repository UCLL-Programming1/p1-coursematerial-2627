import pytest
from p1_util.tests.test_util import call_function


@pytest.mark.parametrize(
    "board,piece,expected",
    [
        # Horizontal win for X
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["O", "O", "-", "-", "-", "-", "-"],
                ["X", "X", "X", "X", "O", "O", "-"],
            ],
            "X",
            True,
        ),

        # Vertical win for X
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "X", "-", "-", "-", "-"],
                ["-", "-", "X", "-", "-", "-", "-"],
                ["O", "-", "X", "-", "-", "-", "-"],
                ["O", "O", "X", "-", "-", "-", "-"],
            ],
            "X",
            True,
        ),

        # Diagonal win for X (bottom-left to top-right)
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "X", "-", "-", "-"],
                ["-", "-", "X", "O", "-", "-", "-"],
                ["-", "X", "O", "O", "-", "-", "-"],
                ["X", "O", "O", "O", "-", "-", "-"],
            ],
            "X",
            True,
        ),

        # Diagonal win for O (bottom-right to top-left)
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["O", "-", "-", "-", "-", "-", "-"],
                ["X", "O", "-", "-", "-", "-", "-"],
                ["X", "X", "O", "-", "-", "-", "-"],
                ["X", "X", "X", "O", "-", "-", "-"],
            ],
            "O",
            True,
        ),

        # Three in a row is not enough
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["O", "-", "-", "-", "-", "-", "-"],
                ["X", "X", "X", "-", "O", "-", "-"],
            ],
            "X",
            False,
        ),

        # Completely filled board without a winner
        (
            [
                ["O", "O", "X", "X", "O", "O", "X"],
                ["X", "X", "O", "O", "X", "X", "O"],
                ["O", "O", "X", "X", "O", "O", "X"],
                ["X", "X", "O", "O", "X", "X", "O"],
                ["O", "O", "X", "X", "O", "O", "X"],
                ["X", "X", "O", "O", "X", "X", "O"],
            ],
            "X",
            False,
        ),

        # Checking the wrong piece should return False
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "X", "-", "-", "-"],
                ["-", "-", "X", "O", "-", "-", "-"],
                ["-", "X", "O", "O", "-", "-", "-"],
                ["X", "O", "O", "O", "-", "-", "-"],
            ],
            "O",
            False,
        ),

        # Horizontal win for O against the right edge (columns 4-7)
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["X", "X", "X", "-", "-", "-", "-"],
                ["X", "X", "X", "O", "O", "O", "O"],
            ],
            "O",
            True,
        ),

        # Horizontal win for X in the top row
        (
            [
                ["-", "-", "-", "X", "X", "X", "X"],
                ["-", "-", "-", "O", "O", "O", "X"],
                ["-", "-", "-", "X", "X", "X", "O"],
                ["-", "-", "-", "O", "O", "O", "X"],
                ["-", "-", "-", "X", "X", "X", "O"],
                ["-", "-", "-", "O", "O", "O", "X"],
            ],
            "X",
            True,
        ),

        # Vertical win for O in the top four rows of the last column
        (
            [
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "-", "X"],
                ["-", "-", "-", "-", "-", "-", "X"],
            ],
            "O",
            True,
        ),

        # Vertical win for X in the first column, top rows
        (
            [
                ["X", "-", "-", "-", "-", "-", "-"],
                ["X", "-", "-", "-", "-", "-", "-"],
                ["X", "-", "-", "-", "-", "-", "-"],
                ["X", "-", "-", "-", "-", "-", "-"],
                ["O", "-", "-", "-", "-", "-", "-"],
                ["O", "-", "-", "-", "-", "-", "-"],
            ],
            "X",
            True,
        ),

        # Diagonal win for X (top-left to bottom-right) ending in the bottom-right corner
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "X", "-", "-", "-"],
                ["-", "-", "-", "O", "X", "-", "-"],
                ["-", "-", "-", "O", "O", "X", "-"],
                ["-", "-", "-", "O", "O", "O", "X"],
            ],
            "X",
            True,
        ),

        # Diagonal win for O (bottom-left to top-right) touching the top row and last column
        (
            [
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "O", "X"],
                ["-", "-", "-", "-", "O", "X", "X"],
                ["-", "-", "-", "O", "X", "X", "O"],
                ["-", "-", "-", "X", "O", "O", "X"],
                ["-", "-", "-", "X", "X", "O", "O"],
            ],
            "O",
            True,
        ),

        # Pieces that would only line up when wrapping around the edge are not four in a row
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["X", "X", "-", "-", "-", "X", "X"],
            ],
            "X",
            False,
        ),

        # Four in a list across two rows is not four in a row
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "X", "X"],
                ["X", "X", "-", "-", "-", "-", "-"],
            ],
            "X",
            False,
        ),

        # A gap in the line: X X - X X is not four in a row
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["X", "X", "-", "X", "X", "-", "-"],
            ],
            "X",
            False,
        ),

        # Three in a column at the top is not enough
        (
            [
                ["-", "-", "-", "-", "-", "-", "X"],
                ["-", "-", "-", "-", "-", "-", "X"],
                ["-", "-", "-", "-", "-", "-", "X"],
                ["-", "-", "-", "-", "-", "-", "O"],
                ["-", "-", "-", "-", "-", "-", "X"],
                ["-", "-", "-", "-", "-", "-", "O"],
            ],
            "X",
            False,
        ),

        # Three on a diagonal is not enough
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "X", "-", "-", "-", "-"],
                ["-", "X", "O", "-", "-", "-", "-"],
                ["X", "O", "O", "-", "-", "-", "-"],
            ],
            "X",
            False,
        ),

        # An empty board has no winner
        (
            [
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
                ["-", "-", "-", "-", "-", "-", "-"],
            ],
            "X",
            False,
        ),
    ]
)
def test_check_winner(board, piece, expected):

    assert call_function(__file__, "check_winner", [board, piece]) == expected
